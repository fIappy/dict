  static IpaPhoneme findBySymbol(String symbol) {
    final clean = symbol.replaceAll('/', '').trim();
    return allWithCambridgeVariants.firstWhere(
      (p) => p.rawSymbol == clean || p.symbol == symbol,
      orElse: () => allPhonemes.first,
    );
  }

