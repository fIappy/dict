  /// 44 个基准音标 + 4 个剑桥美音特例，合计 48 条，与剑桥音标表逐行对应
  static List<IpaPhoneme> get allWithCambridgeVariants => [
        ...allPhonemes,
        ...cambridgeSpecialPhonemes,
      ];

  /// 根据口音筛选音标
  static List<IpaPhoneme> getByAccent(IpaAccent accent) {
    if (accent == IpaAccent.ukOnly) {
      return allPhonemes.where((p) => p.accent == IpaAccent.ukOnly || p.accent == IpaAccent.both).toList();
    } else if (accent == IpaAccent.usOnly) {
      // Return US phonemes from both base and Cambridge specials
      final base = allPhonemes.where((p) => p.accent == IpaAccent.both).toList();
      return [...base, ...cambridgeSpecialPhonemes];
    }
    return allPhonemes;
  }

  /// The entry that carries the other accent's recording for [phoneme].
  ///
  /// `/ɒ/` points at `/ɑː/`, `/ɜː/` at `/ɝː/`, `/əʊ/` at `/oʊ/`; pitches such as
  /// `/ɪə/ -> /ɪr/` have no entry here, and the UI disables that button instead
  /// of playing something that is not on Cambridge's page.
  static IpaPhoneme? counterpartPhoneme(IpaPhoneme phoneme) {
    final symbol = phoneme.counterpartIpa;
    if (symbol == null) return null;
    for (final candidate in allWithCambridgeVariants) {
      if (candidate.symbol == symbol) return candidate;
    }
    return null;
  }
