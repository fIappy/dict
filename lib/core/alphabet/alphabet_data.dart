  static AlphabetLetter findByLetter(String char) {
    final clean = char.trim().toUpperCase();
    return allLetters.firstWhere(
      (l) => l.upper == clean || l.lower == char.trim().toLowerCase(),
      orElse: () => allLetters.first,
    );
  }
